import { chromium } from "playwright";
const BASE = "http://localhost:3000", OUT = "/tmp/claude-0/demo/shots";
(await import("node:fs")).mkdirSync(OUT, { recursive: true });
const b = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" });
const shot = async (ctx, path, file, opts = {}) => {
  const p = await ctx.newPage();
  await p.goto(BASE + path, { waitUntil: "networkidle" });
  await p.waitForTimeout(600);
  await p.screenshot({ path: `${OUT}/${file}.jpg`, type: "jpeg", quality: 72, fullPage: opts.full ?? false });
  await p.close();
};
const dark = await b.newContext({ viewport: { width: 1440, height: 900 }, colorScheme: "dark" });
await shot(dark, "/", "accueil-sombre", { full: true });
const slug = "le-gardien-de-17-ans-qui-fait-douter-les-attaquants-de-regional-1";
await shot(dark, `/articles/${slug}`, "article-sombre", { full: true });
const light = await b.newContext({ viewport: { width: 1440, height: 900 }, colorScheme: "light" });
await shot(light, "/", "accueil-clair", { full: false });
await shot(light, "/mercato", "rubrique-mercato", { full: false });
await shot(light, "/articles/un-milieu-de-national-2-suivi-par-trois-clubs-de-ligue-2", "article-mercato", { full: false });
const mob = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, colorScheme: "dark" });
await shot(mob, "/", "mobile-accueil");
await shot(mob, `/articles/${slug}`, "mobile-article");
const adm = await b.newContext({ viewport: { width: 1440, height: 900 }, colorScheme: "light" });
const p = await adm.newPage();
await p.goto(`${BASE}/admin/login`);
await p.fill("#email", "tom@example.com"); await p.fill("#password", "motdepasse123");
await p.click("button:has-text('Se connecter')"); await p.waitForURL(`${BASE}/admin`);
await p.close();
await shot(adm, "/admin", "admin-tableau-de-bord");
await shot(adm, "/admin/articles/1", "admin-editeur");
await shot(adm, "/admin/articles?vue=kanban", "admin-kanban");
await shot(adm, "/admin/articles?vue=calendrier", "admin-calendrier");
await shot(adm, "/admin/medias", "admin-medias");
await b.close();
console.log("ok");
